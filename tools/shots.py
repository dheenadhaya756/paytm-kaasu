"""Walk every Kaasu journey in Chrome, check for errors, and save screenshots for the deck."""
import os
from playwright.sync_api import sync_playwright
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "pitch")

def pin(pg):
    for k in "1234": pg.click(f"#keypad button:text-is('{k}')")
    pg.wait_for_timeout(700)

with sync_playwright() as p:
    b = p.chromium.launch(channel="chrome")
    pg = b.new_page(viewport={"width": 1100, "height": 1100}, device_scale_factor=2)
    errors = []
    pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
    phone, stage = pg.locator(".phone"), pg.locator(".stage")
    shot = lambda loc, name: loc.screenshot(path=os.path.join(OUT, name))
    nxt = lambda: (pg.click("#jNext"), pg.wait_for_timeout(250))

    pg.goto("http://localhost:3000", wait_until="load"); pg.wait_for_timeout(1200)
    shot(phone, "shot-lang.png")
    pg.click("[data-pick=ta]"); pg.wait_for_timeout(400); shot(phone, "shot-welcome.png")
    pg.click("#getStarted"); pg.wait_for_timeout(3500)
    shot(stage, "shot-before.png"); shot(phone, "shot-home.png")
    print("home:", pg.inner_text(".z-bal"), "|", pg.inner_text(".z-al-t b"))

    # 1. Pongal plan from the Home alert
    pg.click("[data-go=pongal]"); pg.wait_for_timeout(250); shot(phone, "shot-step1.png")
    nxt(); shot(phone, "shot-step2.png"); nxt(); shot(phone, "shot-step3.png"); nxt()
    print("pongal KFS locked:", pg.is_disabled("#jNext"))
    pg.check("#consent"); pg.wait_for_timeout(200); shot(phone, "shot-step4.png")
    nxt(); shot(phone, "shot-step5.png"); nxt(); shot(phone, "shot-pin.png"); pin(pg)
    shot(phone, "shot-done.png"); print("pongal:", pg.inner_text("#doneH"))
    pg.click("#doneHome"); pg.wait_for_timeout(500); shot(stage, "shot-after.png")

    # 2. Savings: new goal, then add money
    pg.click(".tab[data-tab=Savings]"); pg.wait_for_timeout(300)
    pg.click("#paneSavings .p-add"); pg.wait_for_timeout(250)
    print("goal step1 locked until choice:", pg.is_disabled("#jNext"))
    pg.click("[data-set=type][data-val=fridge]"); shot(phone, "shot-goal1.png"); nxt()
    pg.click("[data-set=amount][data-val='25000']"); pg.click("[data-set=months][data-val='6']"); pg.wait_for_timeout(200); shot(phone, "shot-goal2.png"); nxt()
    nxt(); pin(pg); print("goal:", pg.inner_text("#doneH"))
    pg.click("#doneHome"); pg.wait_for_timeout(400); shot(phone, "shot-savings.png")
    pg.locator("#paneSavings [data-go^='flow:add']").last.click(); pg.wait_for_timeout(250); nxt(); pin(pg)
    print("add money:", pg.inner_text("#doneP")); pg.click("#doneHome"); pg.wait_for_timeout(300)

    # 3. Loans: new loan with affordability check
    pg.click(".tab[data-tab=Loans]"); pg.wait_for_timeout(300)
    pg.click("#paneLoans .p-add"); pg.wait_for_timeout(250)
    pg.click("[data-set=purpose][data-val=fridge]"); shot(phone, "shot-loan1.png"); nxt()
    pg.click("[data-set=amount][data-val='100000']"); pg.click("[data-set=days][data-val='30']"); pg.wait_for_timeout(200)
    print("loan 1 lakh / 30 days blocked:", pg.is_disabled("#jNext"), "|", pg.inner_text(".fit b"))
    pg.click("[data-set=amount][data-val='25000']"); pg.click("[data-set=days][data-val='90']"); pg.wait_for_timeout(200)
    print("loan 25k / 90 days:", pg.inner_text(".fit b"), "|", pg.inner_text(".score-line b")); shot(phone, "shot-loan2.png"); nxt()
    print("loan KFS locked:", pg.is_disabled("#jNext")); pg.check("#consent"); pg.wait_for_timeout(150); shot(phone, "shot-loan3.png"); nxt()
    nxt(); pin(pg); print("loan:", pg.inner_text("#doneH")); pg.click("#doneHome"); pg.wait_for_timeout(400); shot(phone, "shot-loans.png")

    # 4. Udhaar: remind one, add new
    pg.click(".tab[data-tab=Udhaar]"); pg.wait_for_timeout(300)
    rem = pg.locator("[data-remind]")
    print("udhaar remind buttons:", rem.count())
    pg.click("#paneUdhaar .p-add"); pg.wait_for_timeout(250); nxt(); nxt(); print("add udhaar:", pg.inner_text("#doneP")); pg.click("#doneHome"); pg.wait_for_timeout(300)
    shot(phone, "shot-udhaar.png")
    print("miss alert shown:", pg.locator("[data-go='flow:miss']").count())
    pg.click("[data-go='flow:miss']"); pg.wait_for_timeout(250); shot(phone, "shot-miss1.png")
    print("miss:", pg.inner_text(".j-h"), "|", pg.locator(".row-kv.bad b").first.inner_text()); nxt()
    print("fix locked until choice:", pg.is_disabled("#jNext"))
    pg.click("[data-set=fix][data-val=save]"); pg.wait_for_timeout(200); shot(phone, "shot-miss2.png"); nxt(); nxt(); pin(pg)
    print("miss done:", pg.inner_text("#doneP")); pg.click("#doneHome"); pg.wait_for_timeout(300)
    print("reminder sender:", "Paytm" in pg.content() and "Payment reminder" in open(r"public/app.js",encoding="utf-8").read())
    print("udhaar timing:", pg.locator("#paneUdhaar .pd").first.inner_text())
    pg.click(".tab[data-tab=Savings]"); pg.wait_for_timeout(300); shot(phone, "shot-score.png")
    print("save score:", pg.inner_text(".sc-num"), "| rate:", pg.inner_text(".sc-rate b"))
    pg.click(".tab[data-tab=Loans]"); pg.wait_for_timeout(300)
    pg.click("#rainBtn"); pg.wait_for_timeout(900); shot(phone, "shot-rain.png"); shot(stage, "shot-rain-stage.png")
    print("rain:", pg.inner_text(".rain .gc-t small"), "| loan pill:", pg.locator("#paneLoans .goal-card .pill").first.inner_text())
    # 5. Grow with Kaasu
    pg.click(".tab[data-tab=Home]"); pg.wait_for_timeout(300); shot(phone, "shot-home2.png")
    pg.click("[data-go='flow:fund']"); pg.wait_for_timeout(250); shot(phone, "shot-fund1.png"); nxt(); shot(phone, "shot-fund2.png"); nxt(); nxt(); pin(pg)
    print("fund:", pg.inner_text("#doneH"), "|", pg.inner_text("#doneP")); pg.click("#doneHome"); pg.wait_for_timeout(300)
    pg.click("[data-go='flow:circle']"); pg.wait_for_timeout(250); nxt(); shot(phone, "shot-circle2.png"); nxt(); nxt(); pin(pg)
    print("circle:", pg.inner_text("#doneP")); pg.click("#doneHome"); pg.wait_for_timeout(300)
    pg.click("[data-go='flow:bill']"); pg.wait_for_timeout(250); shot(phone, "shot-bill1.png")
    pg.click("#billSample"); pg.wait_for_selector("#jStep:has-text('Step 2')", timeout=60000); pg.wait_for_timeout(300); shot(phone, "shot-bill2.png")
    print("bill:", pg.inner_text(".j-h")); nxt(); print("bill done:", pg.inner_text("#doneP")); pg.click("#doneHome"); pg.wait_for_timeout(300)
    print("grow tiles:", " | ".join(pg.inner_text(".z-grow").splitlines()))
    # 6. New: Staff advance, Galla check, Bharosa, confirmed udhaar, Paytm tools
    print("paytm tools:", pg.locator(".svc button").count()); pg.locator(".svc button").first.click(); pg.wait_for_timeout(300)
    pg.click("[data-go='flow:staff']"); pg.wait_for_timeout(400); shot(phone, "shot-staff1.png"); print("staff:", pg.inner_text(".j-h"), "| sb:", pg.inner_text("#sbText")[:40])
    nxt(); pg.click("[data-set=amount][data-val='2000']"); pg.wait_for_timeout(200); shot(phone, "shot-staff2.png"); nxt(); nxt(); pin(pg)
    print("staff done:", pg.inner_text("#doneP")); pg.click("#doneHome"); pg.wait_for_timeout(300)
    pg.click("[data-go='flow:galla']"); pg.wait_for_timeout(400); print("galla locked:", pg.is_disabled("#jNext"))
    pg.click("[data-set=counted][data-val='3050']"); pg.wait_for_timeout(200); shot(phone, "shot-galla1.png"); nxt(); shot(phone, "shot-galla2.png")
    print("galla:", pg.inner_text(".j-h")); nxt(); print("galla done:", pg.inner_text("#doneP")); pg.click("#doneHome"); pg.wait_for_timeout(300)
    pg.click(".tab[data-tab=Udhaar]"); pg.wait_for_timeout(400)
    print("confirmed tags:", pg.locator("#paneUdhaar .ok-tag").count(), "| awaiting:", pg.locator("#paneUdhaar .wait-tag").count())
    pg.click("#paneUdhaar .bh-card"); pg.wait_for_timeout(400); shot(phone, "shot-bharosa1.png"); print("bharosa:", pg.inner_text(".j-h"))
    nxt(); shot(phone, "shot-bharosa2.png"); nxt(); shot(phone, "shot-bharosa3.png"); nxt(); pin(pg)
    print("bharosa done:", pg.inner_text("#doneP")); pg.click("#doneHome"); pg.wait_for_timeout(5000)
    shot(phone, "shot-bharosa-after.png"); print("bharosa card:", pg.inner_text("#paneUdhaar .bh-card b"), "| paid rows:", pg.locator("#paneUdhaar .sent:has-text('Bharosa')").count())
    pg.click("#paneUdhaar .p-add"); pg.wait_for_timeout(300); nxt(); shot(phone, "shot-confirm.png"); nxt(); pg.click("#doneHome"); pg.wait_for_timeout(2800)
    print("new entry confirmed:", pg.locator("#paneUdhaar .ok-tag").count())
    pg.click(".tab[data-tab=Home]"); pg.wait_for_timeout(400); shot(phone, "shot-home3.png")
    print("grow tiles after:", " | ".join(pg.inner_text(".z-grow").splitlines()))
    pg.click("#voiceTab"); pg.wait_for_timeout(300); shot(phone, "shot-voice.png")

    pg.set_viewport_size({"width": 390, "height": 844})
    pg.goto("http://localhost:3000/#home", wait_until="load"); pg.wait_for_timeout(1500)
    print("mobile scrollWidth:", pg.evaluate("document.documentElement.scrollWidth"))
    print("errors:", errors[:10])
    b.close()
